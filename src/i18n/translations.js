const normalizeTranslationKey = (value) => String(value || '').replace(/\s+/g, ' ').trim();

const normalizedArabicTranslations = Object.entries(arabicTranslations).reduce((acc, [key, value]) =>
{
    acc[normalizeTranslationKey(key)] = value;
    return acc;
}, {});

export const translateText = (value, language = DEFAULT_LANGUAGE) =>
{
    if (value === undefined || value === null) return '';
    if (language !== LANGUAGES.ar.code) return value;

    const text = String(value);
    const normalizedText = normalizeTranslationKey(text);

    return arabicTranslations[text] || normalizedArabicTranslations[normalizedText] || text;
};
